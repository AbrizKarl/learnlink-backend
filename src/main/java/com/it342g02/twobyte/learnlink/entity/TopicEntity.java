package com.it342g02.twobyte.learnlink.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

@Entity
@Table(name = "topic")
public class TopicEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private int topicId;

    private int subjectId;          // links to SUBJECT (kept as a plain number for this simple CRUD)
    private String title;           // e.g. "Cause and Effect"

    @Column(columnDefinition = "TEXT")
    private String lessonContent;

    // constructors
    public TopicEntity() {
    }

    public TopicEntity(int subjectId, String title, String lessonContent) {
        this.subjectId = subjectId;
        this.title = title;
        this.lessonContent = lessonContent;
    }

    // getters
    public int getTopicId() { return topicId; }
    public int getSubjectId() { return subjectId; }
    public String getTitle() { return title; }
    public String getLessonContent() { return lessonContent; }

    // setters (topicId is generated by the database, so it has no setter)
    public void setSubjectId(int subjectId) { this.subjectId = subjectId; }
    public void setTitle(String title) { this.title = title; }
    public void setLessonContent(String lessonContent) { this.lessonContent = lessonContent; }
}
